def _signal(name: str) -> np.ndarray:
    n = 64
    t = np.arange(n, dtype=float) / n
    if name == "noise":
        return np.random.default_rng(1367).normal(size=n)
    if name == "chirp":
        return np.cos(2 * np.pi * (2 * t + 10 * t**2) + 0.3)
    if name == "sine":
        return np.sin(2 * np.pi * (5.25 * t) + 0.1)
    impulse = np.zeros(n)
    impulse[n // 3] = 1.0
    return impulse


@pytest.mark.parametrize("name", tuple(_EXPECTED))
def test_default_meyer_matches_frozen_prechange_coefficients(
    name: str, backend_name: str
) -> None:
    data = _signal(name)
    expected = np.fromstring(_EXPECTED[name], sep=" ").reshape(1, 8, 9)
    series = TimeSeries(data, dt=0.25, backend=backend_name)
    coeffs = series.to_wdm(nt=8)
    from_frequency = WDM.from_frequency_series(
        FrequencySeries(np.fft.fft(data), df=1 / 16, backend=backend_name), nt=8
    )
    for result in (coeffs, from_frequency):
        np.testing.assert_allclose(
            np.asarray(result.coeffs), expected, rtol=2e-12, atol=2e-12
        )
        np.testing.assert_allclose(
            np.asarray(result.to_time_series().data[0]),
            data,
            rtol=2e-12,
            atol=2e-12,
        )


def test_meyer_constructor_positional_metadata_remains_compatible() -> None:
    coeffs = TimeSeries(_signal("noise"), dt=0.25).to_wdm(nt=8)
    rebuilt = WDM(coeffs.coeffs, 0.25, 1 / 3, 1, "numpy")
    np.testing.assert_array_equal(rebuilt.coeffs, coeffs.coeffs)
    np.testing.assert_allclose(
        rebuilt.to_time_series().data,
        coeffs.to_time_series().data,
        rtol=2e-12,
        atol=2e-12,
    )
